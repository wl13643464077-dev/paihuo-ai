def build() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    written = 0
    for industry in INDUSTRIES:
        doc = {
            "key": industry["key"],
            "name": industry["name"],
            "as_of": AS_OF,
            # 指标 = 通用门店口径 + 本行业专属口径。专属项排在前面,注入时优先命中。
            "metrics": industry["metrics"] + COMMON_METRICS,
            # 见文件头:只收可指名到机构与年份、且口径能对得上的公开数据;
            # 其余行业留空,由提示词显式要求员工去要老板的真实数据,而不是凭印象编。
            "benchmarks": BENCHMARKS.get(industry["key"], []),
            "benchmarks_note": (
                "参考区间仅为量级参照，必须结合本店实际重新测算；"
                "与老板提供的数据冲突时以老板的数据为准。"
                "尚无参考区间的行业表示本系统未接入该行业的授权数据源，"
                "此时不得凭印象给出行业均值，应改用老板的历史数据测算或列为「待补数据」。"
                "补充新条目时每条必须同时具备 metric/range/source/scope/as_of 五项。"
            ),
            "glossary": industry["glossary"],
            "practices": industry["practices"],
            "compliance": industry["compliance"],
            "pitfalls": industry["pitfalls"],
        }
        path = os.path.join(OUT_DIR, f"{industry['key']}.json")
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(doc, handle, ensure_ascii=False, indent=1)
            handle.write("\n")
        written += 1
    print(f"已生成 {written} 个行业知识底座 → {OUT_DIR}")
    print("提示:benchmarks 为空是刻意设计,见本脚本文件头说明。")
    return 0


if __name__ == "__main__":
    raise SystemExit(build())
