def _public_role(
    focus: str,
    materials: str,
    scope_tip: str,
    situation_tip: str,
    decision_tip: str,
    output_hint: str,
) -> dict:
    """声明一份手写公开派活文案。

    这些参数只描述客户可以主动提供的业务信息，不读取岗位档案。保留这个小构造器
    是为了让 97 个精确岗位条目可审计，而不是重新引入关键词推断或默认模板。
    """
    return {
        "focus": focus,
        "materials": materials,
        "input_tips": (scope_tip, situation_tip, decision_tip),
        "output_hint": output_hint,
    }


