def _upsert_by(rows: Iterable[dict], additions: Iterable[dict], field: str) -> list[dict]:
    additions = tuple(additions)
    replacement = {row[field]: row for row in additions}
    kept = [row for row in rows if row.get(field) not in replacement]
    return kept + [dict(row) for row in additions]


def build(industry: str) -> dict:
    path = CATALOG_DIR / f"{industry}.json"
    catalog = json.loads(path.read_text(encoding="utf-8"))
    specs = HOTEL_SPECS if industry == "hotel" else FITNESS_SPECS
    expected = set(range(1501, 1537) if industry == "hotel" else range(1701, 1737))
    if set(specs) != expected:
        raise ValueError(f"{industry}: RoleSpec 不是完整36岗")
    employees = [_render_employee(industry, catalog, employee, specs[employee["idx"]])
                 for employee in catalog["employees"]]
    ranked = sorted(
        employees,
        key=lambda employee: (
            -employee["priority_score"]["total"],
            -employee["priority_score"]["usage_frequency"],
            -employee["priority_score"]["economic_value"],
            -employee["priority_score"]["pain_severity"],
            -employee["priority_score"]["data_availability"],
            employee["idx"],
        ),
    )
    for rank, employee in enumerate(ranked, 1):
        employee["priority_rank"] = rank
    catalog["catalog_version"] = "2026.08.v3"
    catalog["as_of"] = "2026-08-12"
    catalog["identity_policy"] = "保留全部36名原员工的idx、person、key、name、group；全员当前在岗，无降级、无合并、无删减。"
    catalog["selection_policy"] = "逐岗以行业高频高价值痛点、企业可得数据和人工负责边界构建；低频生命安全与经营连续岗保留且按真实频率评分。"
    catalog["sources"] = _upsert_by(catalog["sources"], SOURCE_ADDITIONS[industry], "id")
    catalog["pain_points"] = _upsert_by(catalog["pain_points"], PAIN_ADDITIONS[industry], "code")
    catalog["employees"] = employees
    return catalog


def _render_json(catalog: dict) -> str:
    return json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"


def _metric_rows(catalogs: dict[str, dict]) -> list[tuple[str, dict, dict]]:
    return [
        (industry, employee, metric)
        for industry, catalog in catalogs.items()
        for employee in catalog.get("employees", [])
        for metric in employee.get("decision_contract", {}).get("success_metrics", [])
    ]


def _canonical_authored(value: object, catalog: dict, employee: dict) -> str:
    """Remove identity and referenced I/O nouns before structure comparison.

    This makes a copied workflow or KPI skeleton visible even when somebody
    changes the employee name, business object, input, output, or KPI title.
    Formula bodies, windows, escalation owners/actions, and learning methods
    remain in place and therefore have to be genuinely role-specific.
    """
    text = value if isinstance(value, str) else json.dumps(
        value, ensure_ascii=False, sort_keys=True,
    )
    contract = employee["decision_contract"]
    profile = employee["professional_profile"]
    tokens = [
        employee.get(field) for field in (
            "name", "key", "group", "role", "duty", "desc", "intro",
            "primary_decision", "person", "idx", "num",
        )
    ]
    tokens.extend(catalog.get(field) for field in ("name", "industry", "key"))
    tokens.extend(contract.get("required_inputs", []))
    tokens.extend(contract.get("outputs", []))
    tokens.extend(profile.get("data_objects", []))
    tokens.extend(
        metric.get("name")
        for metric in contract.get("success_metrics", [])
        if isinstance(metric, dict)
    )
    for token in sorted({str(token) for token in tokens if token}, key=len, reverse=True):
        text = text.replace(token, "")
    text = SELF_AUDIT_REMOVABLE.sub("", text)
    return re.sub(r"[^\w\u4e00-\u9fff]+", "", text).lower()


def _pairwise_max(
    rows: list[tuple[str, int, str]], *, skip_same_employee: bool = False,
) -> tuple[float, tuple[int, int] | None]:
    maximum = 0.0
    pair = None
    for left in range(len(rows)):
        for right in range(left + 1, len(rows)):
            if skip_same_employee and rows[left][:2] == rows[right][:2]:
                continue
            ratio = SequenceMatcher(None, rows[left][2], rows[right][2]).ratio()
            if ratio > maximum:
                maximum = ratio
                pair = (left, right)
    return maximum, pair


def _require_distinct_structures(
    label: str,
    rows: list[tuple[str, int, str]],
    *,
    skip_same_employee: bool = False,
) -> float:
    values = [row[2] for row in rows]
    if len(values) != len(set(values)):
        raise ValueError(f"{label}: 去身份/输入/输出后存在完全重复骨架")
    maximum, pair = _pairwise_max(rows, skip_same_employee=skip_same_employee)
    if pair is not None and maximum >= 0.86:
        left, right = pair
        raise ValueError(
            f"{label}: {rows[left][0]}/{rows[left][1]} vs "
            f"{rows[right][0]}/{rows[right][1]} similarity={maximum:.4f}"
        )
    return maximum


def _validate_owned_catalogs(catalogs: dict[str, dict]) -> dict[str, float]:
    """Fail before writing if authored hotel/fitness content regresses to templates."""
    employees = [
        (industry, catalog, employee)
        for industry, catalog in catalogs.items()
        for employee in catalog.get("employees", [])
    ]
    if len(employees) != 72:
        raise ValueError("酒店/健身必须各保留36名原员工")

    metric_rows = _metric_rows(catalogs)
    if len(metric_rows) != 216:
        raise ValueError("酒店/健身72岗必须每岗显式定义3项KPI")
    for industry, employee, metric in metric_rows:
        who = f"{industry}/{employee['idx']}/{metric.get('key')}"
        formula = str(metric.get("formula") or "").strip()
        if any(pattern.search(formula) for pattern in GENERIC_METRIC_FORMULAS):
            raise ValueError(f"{who}: 公式仍是技能/对象替换模板")
        if not any(operator in formula for operator in ("÷", "−", "Σ")):
            raise ValueError(f"{who}: 缺少可执行的业务计算口径")
        if "× 100%" in formula and "分母为0时记N/A" not in formula:
            raise ValueError(f"{who}: 百分比公式缺失零分母策略")
        required = employee["decision_contract"]["required_inputs"]
        source = str(metric.get("source") or "")
        if not all(value in source for value in required[:2]):
            raise ValueError(f"{who}: KPI未回链前两项必需底账")
    for field in ("key", "name", "formula"):
        values = [metric[field] for _industry, _employee, metric in metric_rows]
        if len(values) != len(set(values)):
            raise ValueError(f"酒店/健身216项KPI {field} 必须逐项唯一")

    getters = {
        "workflow": lambda employee: employee["decision_contract"]["workflow"],
        "metrics": lambda employee: [
            {key: metric[key] for key in ("name", "formula", "window", "source")}
            for metric in employee["decision_contract"]["success_metrics"]
        ],
        "learning": lambda employee: employee["professional_profile"]["learning_tracks"],
        "escalation": lambda employee: employee["professional_profile"]["escalation_matrix"],
    }
    stats: dict[str, float] = {}
    for label, getter in getters.items():
        rows = [
            (industry, employee["idx"], _canonical_authored(getter(employee), catalog, employee))
            for industry, catalog, employee in employees
        ]
        stats[label] = _require_distinct_structures(label, rows)

    workflow_steps = [
        (industry, employee["idx"], _canonical_authored(step, catalog, employee))
        for industry, catalog, employee in employees
        for step in employee["decision_contract"]["workflow"]
    ]
    stats["workflow_step"] = _require_distinct_structures(
        "workflow_step", workflow_steps, skip_same_employee=True,
    )
    formula_structures = [
        (industry, employee["idx"], _canonical_authored(metric["formula"], catalog, employee))
        for industry, catalog, employee in employees
        for metric in employee["decision_contract"]["success_metrics"]
    ]
    stats["metric_formula"] = _require_distinct_structures(
        "metric_formula", formula_structures, skip_same_employee=True,
    )
    return stats


def _validate_global_metric_uniqueness(owned: dict[str, dict]) -> None:
    catalogs = {}
    for path in sorted(CATALOG_DIR.glob("*.json")):
        catalogs[path.stem] = owned.get(
            path.stem,
            json.loads(path.read_text(encoding="utf-8")),
        )
    metrics = _metric_rows(catalogs)
    if len(catalogs) != 10 or len(metrics) != 1080:
        raise ValueError("全局KPI唯一性审计需要10业×36岗×3项完整目录")
    for field in ("key", "name", "formula"):
        values = [metric[field] for _industry, _employee, metric in metrics]
        if len(values) != len(set(values)):
            raise ValueError(f"全局1080项KPI {field} 存在重复")


def _write(industry: str, catalog: dict) -> None:
    path = CATALOG_DIR / f"{industry}.json"
    path.write_text(_render_json(catalog), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--industry", choices=("hotel", "fitness", "all"), default="all")
    parser.add_argument("--check", action="store_true", help="只构建和校验，不写入JSON")
    args = parser.parse_args()
    catalogs = {industry: build(industry) for industry in ("hotel", "fitness")}
    similarity = _validate_owned_catalogs(catalogs)
    _validate_global_metric_uniqueness(catalogs)
    industries = ("hotel", "fitness") if args.industry == "all" else (args.industry,)
    stale = []
    for industry in industries:
        catalog = catalogs[industry]
        if len(catalog["pain_points"]) != 8 or len(catalog["employees"]) != 36:
            raise ValueError(f"{industry}: catalog cardinality invalid")
        payload = _render_json(catalog)
        path = CATALOG_DIR / f"{industry}.json"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != payload:
                stale.append(industry)
        else:
            _write(industry, catalog)
        digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
        print(
            f"{industry}: pains={len(catalog['pain_points'])} "
            f"employees={len(catalog['employees'])} sha256={digest}"
        )
    print(
        "self-audit: "
        + " ".join(f"{field}={score:.4f}" for field, score in similarity.items())
    )
    if stale:
        print("OUT-OF-DATE: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
