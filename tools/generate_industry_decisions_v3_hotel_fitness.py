def L(value: str) -> tuple[str, ...]:
    return tuple(part.strip() for part in value.split("|") if part.strip())


def T(value: str) -> tuple[tuple[str, str], ...]:
    rows = []
    for part in L(value):
        tool, scope = part.split("=>", 1)
        rows.append((tool.strip(), scope.strip()))
    return tuple(rows)


def E(value: str) -> tuple[tuple[str, str, str], ...]:
    rows = []
    for part in L(value):
        condition, owner, action = part.split("=>", 2)
        rows.append((condition.strip(), owner.strip(), action.strip()))
    return tuple(rows)


@dataclass(frozen=True)
class RoleSpec:
    decision: str
    secondary: str
    scope: str
    inputs: tuple[str, ...]
    workflow: tuple[str, ...]
    outputs: tuple[str, ...]
    knowledge: tuple[str, ...]
    objects: tuple[str, ...]
    tools: tuple[tuple[str, str], ...]
    skills: tuple[str, ...]
    capabilities: tuple[str, ...]
    rhythm: tuple[str, str, str]
    escalation: tuple[tuple[str, str, str], ...]
    learning: tuple[str, ...]
    metrics: tuple[tuple[str, str, str, tuple[int, ...]], ...]
    score: tuple[int, int, int, int]
    cadence: str
    pains: tuple[str, ...] | None = None


def r(*, d: str, d2: str, sc: str, inp: str, wf: str, out: str,
      know: str, obj: str, tool: str, skill: str, cap: str, rhythm: str,
      esc: str, learn: str, metrics: tuple[tuple[str, str, str, tuple[int, ...]], ...], score: str,
      cadence: str, pains: str | None = None) -> RoleSpec:
    score_tuple = tuple(int(value) for value in score)
    if len(score_tuple) != 4:
        raise ValueError(f"score 必须是4位整数: {score}")
    rhythm_tuple = L(rhythm)
    if len(rhythm_tuple) != 3:
        raise ValueError("节奏必须依次为 daily/event/review")
    if len(metrics) != 3:
        raise ValueError(f"{d}: 必须显式声明3个岗位原生KPI")
    for name, formula, window, source_inputs in metrics:
        if not all((name.strip(), formula.strip(), window.strip())):
            raise ValueError(f"{d}: KPI名称、公式与窗口不得为空")
        if not source_inputs or any(not 0 <= index < len(L(inp)) for index in source_inputs):
            raise ValueError(f"{d}: KPI必须显式绑定有效输入")
    return RoleSpec(
        decision=d, secondary=d2, scope=sc, inputs=L(inp), workflow=L(wf),
        outputs=L(out), knowledge=L(know), objects=L(obj), tools=T(tool),
        skills=L(skill), capabilities=L(cap), rhythm=rhythm_tuple,
        escalation=E(esc), learning=L(learn), metrics=metrics,
        score=score_tuple, cadence=cadence, pains=L(pains) if pains else None,
    )


